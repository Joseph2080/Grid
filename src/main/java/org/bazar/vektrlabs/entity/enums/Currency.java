package org.bazar.vektrlabs.entity.enums;

/**
 * Curated set of settlement currencies a store may be created with.
 * Each store has exactly one currency; the platform is "multi-currency"
 * in the sense that different stores may each use a different one.
 */
public enum Currency {
    USD,
    EUR,
    GBP,
    ZAR,
    NGN,
    KES,
    GHS,
    CAD,
    AUD
}
